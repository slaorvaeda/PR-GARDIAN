import React, { useState } from 'react';
import { X, TestTube2, Copy, CheckCheck, FileCode } from 'lucide-react';

export default function SynthesizedTestsModal({ tests = [], isOpen, onClose }) {
  const [selectedIdx, setSelectedIdx] = useState(0);
  const [copied, setCopied] = useState(false);

  if (!isOpen || tests.length === 0) return null;

  const currentTest = tests[selectedIdx] || tests[0];

  const handleCopy = () => {
    navigator.clipboard.writeText(currentTest.test_code);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fade-in">
      <div className="border border-[#30363d] rounded-2xl bg-[#161b22] w-full max-w-4xl max-h-[85vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-[#30363d] flex items-center justify-between bg-[#21262d]/40">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-cyan-500/10 text-cyan-400 border border-cyan-500/20 flex items-center justify-center">
              <TestTube2 className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-white">Synthesized Unit Test Suites</h3>
              <p className="text-xs text-[#8b949e]">Auto-generated by LangGraph Test Agent for untested logic</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-[#8b949e] hover:text-white hover:bg-[#30363d] transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tab selector */}
        <div className="flex items-center gap-2 px-6 py-2.5 border-b border-[#30363d] bg-[#0d1117] overflow-x-auto">
          {tests.map((t, idx) => (
            <button
              key={t.id}
              onClick={() => setSelectedIdx(idx)}
              className={`flex items-center gap-2 px-3 py-1.5 rounded-lg text-xs font-mono transition-all ${
                idx === selectedIdx
                  ? 'bg-[#21262d] text-white border border-[#30363d] shadow-sm'
                  : 'text-[#8b949e] hover:text-[#c9d1d9]'
              }`}
            >
              <FileCode className="w-3.5 h-3.5 text-cyan-400" />
              <span>{t.target_function}()</span>
              <span className="text-[10px] px-1.5 py-0.2 rounded bg-cyan-500/20 text-cyan-300 font-bold uppercase">
                {t.test_framework}
              </span>
            </button>
          ))}
        </div>

        {/* Test Code Box */}
        <div className="flex-1 p-6 overflow-y-auto bg-[#0d1117]">
          <div className="flex items-center justify-between mb-3 text-xs text-[#8b949e]">
            <span className="font-mono text-[#58a6ff]">{currentTest.file_path}</span>
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1 rounded-lg bg-[#21262d] hover:bg-[#30363d] text-white transition-all text-xs font-semibold"
            >
              {copied ? <CheckCheck className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Test Code'}</span>
            </button>
          </div>
          <pre className="p-4 rounded-xl border border-[#30363d] bg-[#161b22] text-[#7ee787] font-mono text-xs overflow-x-auto leading-relaxed">
            {currentTest.test_code}
          </pre>
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-[#30363d] bg-[#21262d]/30 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-lg bg-[#30363d] hover:bg-[#484f58] text-white text-xs font-semibold"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
